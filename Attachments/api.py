"""Shared public attachment response formatter.

The only mounted attachment API is defined in the consolidated all_apis.py.
This module does not register an independent router.
"""
from __future__ import annotations
from typing import Any

# Earlier compact source referenced this name but never defined it.
# Scanner failures and high-impact attachment policy violations must appear
# with the appropriate severity in the client response.
CRITICAL_DISPLAY_CODES = frozenset({
    'OCR_UNAVAILABLE', 'OCR_FAILED', 'OCR_DISABLED', 'SCANNER_FAILURE',
    'CLAMAV_UNAVAILABLE', 'CLAMAV_ERROR', 'ANTIVIRUS_UNAVAILABLE',
    'ML_UNAVAILABLE', 'CONTENT_UNINSPECTABLE', 'CONTENT_SCAN_FAILED',
    'CONTENT_SCANNER_FAILURE', 'PARSER_FAILURE', 'SCAN_INCOMPLETE',
    'MALWARE_DETECTED', 'HASH_DENYLIST', 'ZIP_BOMB', 'ZIP_TRAVERSAL',
    'CONTENT_LIMIT', 'VISUAL_CONTENT_NOT_CLASSIFIED',
})

def format_public_response(report: dict[str, Any]) -> dict[str, Any]:
    """Convert an existing scanner result to the response in error_response.txt.

    IMPORTANT: Keep the original `report` unchanged for server-side decisions.
    """
    status = report['status']

    def simplify_issue(issue: dict[str, Any], *, advisory: bool) -> dict[str, str]:
        code = str(issue.get('code', 'UNKNOWN'))
        severity = issue.get('severity')
        if not severity:
            severity = ('MINOR' if advisory else
                        'CRITICAL' if code in CRITICAL_DISPLAY_CODES else 'HIGH')
        reason = str(issue.get('reason', 'Attachment policy violation detected'))
        if code == 'SOFT_REPLY_URGENCY':
            reason = 'Attachment requests a rapid reply.'
        return {
            'code': code,
            'severity': str(severity).upper(),
            'reason': reason,
        }

    attachments = []
    for item in report.get('attachments', []):
        # Restricted findings and low-level advisories share one public list.
        issues = [simplify_issue(x, advisory=False) for x in item.get('findings', [])]
        issues.extend(simplify_issue(x, advisory=True) for x in item.get('advisories', []))
        attachments.append({
            'filename': item.get('filename'),
            'status': item.get('status'),
            'detected_type': item.get('detected_type'),
            'antivirus': item.get('antivirus', 'NOT_RUN'),
            'confidence_score': item.get('confidence_score'),
            'issues': issues,
        })

    warnings: list[str] = []
    additional_warnings = [
        warning
        for item in report.get('attachments', [])
        for warning in item.get('content_warnings', [])
    ]
    for warning in list(report.get('warnings', [])) + additional_warnings:
        warning = str(warning)
        if warning.startswith('Malware scanning is disabled'):
            warning = 'Malware scanning is disabled.'
        if warning not in warnings:
            warnings.append(warning)

    popup: dict[str, Any] | None = None
    if status == 'WARNING':
        popup = {
            'show': True,
            'type': 'WARNING',
            'title': 'Attachment Warning',
            'message': 'Review the attachment before sending.',
            'actions': ['EDIT_MAIL', 'CLOSE'],
        }
    elif status == 'RESTRICTED':
        message = 'Remove or correct the restricted attachment and validate again.'
        if not attachments:
            # Early limits / scanner failures have no per-file issues yet.
            # Preserve the actual blocking reason rather than hiding it.
            raw_reasons = (report.get('popup') or {}).get('reasons', [])
            details = [str(x.get('reason', '')) for x in raw_reasons if x.get('reason')]
            if details:
                message += ' Reason: ' + '; '.join(details)
        popup = {
            'show': True,
            'type': 'RESTRICTED',
            'title': 'Attachment Restricted',
            'message': message,
            'actions': ['DISCARD_MAIL'],
        }

    result = {
        'status': status,
        'can_send': report.get('can_send', False),
        'confidence_score': report.get('confidence_score'),
        'requires_acknowledgement': report.get('requires_acknowledgement', False),
        # Other independent modules in the parent Email Validator populate these.
        'text': [],
        'URL': [],
        'attachments': attachments,
        'warnings': warnings,
        'popup': popup,
    }
    # WARNING token is cryptographically generated by the original code.
    # Never replace it with a fixed sample token.
    if status == 'WARNING' and report.get('warning_challenge'):
        result['warning_challenge'] = report['warning_challenge']
    return result


